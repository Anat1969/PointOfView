/** מזהי הקלפים: w-1..60, q-1..60. התמונות הן קלפי האימון (coach-...) */
export const wordId = (i: number) => `w-${i + 1}`;
export const questionId = (i: number) => `q-${i + 1}`;
export const clarityText = (refId: string) => {
  const n = Number(refId.slice(2)) - 1;
  if (refId.startsWith('w-')) return CLARITY_WORDS[n];
  if (refId.startsWith('q-')) return CLARITY_QUESTIONS[n];
  return undefined;
};
